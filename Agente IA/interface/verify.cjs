const path = require('path');
const fs = require('fs');
const {pathToFileURL} = require('url');
const {chromium} = require('../../node_modules/playwright-core');
const assert = require('node:assert/strict');
(async()=>{
 const out=path.join(__dirname,'output');fs.mkdirSync(out,{recursive:true});
 const browser=await chromium.launch({headless:true,channel:'msedge'});
 const page=await browser.newPage({viewport:{width:1440,height:1060},deviceScaleFactor:1.5});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(pathToFileURL(path.join(__dirname,'index.html')).href);
 await page.screenshot({path:path.join(out,'mockup-desktop.png'),fullPage:true});
 assert.deepEqual(await page.locator('.metric-value').allTextContents(),['24','18','51','96.1 %']);
 await page.getByRole('button',{name:'Hoy',exact:true}).click();
 assert.deepEqual(await page.locator('.metric-value').allTextContents(),['4','3','8','100.0 %']);
 await page.getByRole('button',{name:'Últimos 3 días',exact:true}).click();
 assert.deepEqual(await page.locator('.metric-value').allTextContents(),['12','8','24','95.8 %']);
 await page.getByRole('button',{name:'Últimos 7 días',exact:true}).click();
 await page.locator('[data-tab="actividad"]').click();
 await page.locator('#status').selectOption('error');
 assert.equal(await page.locator('#activity-table tbody tr').count(),2);
 await page.locator('#search').fill('no-existe');
 assert.match(await page.locator('#activity-table').innerText(),/No hay operaciones/);
 await page.locator('#search').fill('');
 const downloadPromise=page.waitForEvent('download');await page.locator('#export').click();
 const download=await downloadPromise;const csvPath=path.join(out,'reporte-ejemplo.csv');await download.saveAs(csvPath);
 assert.equal(fs.readFileSync(csvPath,'utf8').trim().split(/\r?\n/).length,3);
 await page.locator('#toast').evaluate(e=>e.style.display='none');
 await page.locator('#status').selectOption('all');
 await page.locator('[data-tab="configuracion"]').click();
 await page.screenshot({path:path.join(out,'mockup-configuracion.png'),fullPage:true});
 await page.locator('#project-select').selectOption('inventory');
 await page.locator('#show-summary').click();
 assert.equal(await page.locator('#project').innerText(),'Almacén');
 assert.match(await page.locator('#metrics').innerText(),/Entradas registradas/);
 await page.screenshot({path:path.join(out,'mockup-reutilizacion.png'),fullPage:true});
 await page.locator('[data-tab="configuracion"]').click();
 await page.locator('#project-select').selectOption('dental');await page.locator('#show-summary').click();
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:path.join(out,'mockup-mobile.png'),fullPage:true});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
 await page.locator('[data-tab="actividad"]').click();
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
 assert.deepEqual(errors,[]);
 const result={status:'passed',checks:['Indicadores de 7 días: 24 altas, 18 fotos, 51 operaciones, 96.1 % de éxito','Periodo de hoy: 8 operaciones, 100 % de éxito','Periodo de 3 días: 24 operaciones, 95.8 % de éxito','Filtro de fallidas: 2 registros','Búsqueda sin coincidencias: estado vacío','CSV filtrado: encabezado y 2 registros','Configuración de inventario cambia identidad y métricas','390 px sin desbordamiento de página en resumen y actividad','Sin errores JavaScript'],scope:'Prototipo local con datos simulados; sin conexión a API o ESP'};
 fs.writeFileSync(path.join(out,'verificacion.json'),JSON.stringify(result,null,2));
 await browser.close();console.log(JSON.stringify(result,null,2));
})().catch(e=>{console.error(e);process.exit(1)});
